        SELECT ID, NAME, VALUE
        FROM T_0042
        ORDER BY ID;

    -- レコード変数の宣言
    v_item_rec c_items%ROWTYPE;
BEGIN
    -- カーソルを開く
    OPEN c_items;

    -- 最初のレコードを取得
    FETCH c_items INTO v_item_rec;
    DBMS_OUTPUT.PUT_LINE('最初のレコード: ID=' || v_item_rec.ID || ', NAME=' || v_item_rec.NAME);

