CREATE OR REPLACE PROCEDURE "SCHEMA_SAMPLE".SCT_0008_JSON_ARRAY_DEMO(
    p_id IN NUMBER,
    p_name IN VARCHAR2
)
IS
    -- JSON配列オブジェクトを宣言
    v_json_array JSON_ARRAY_T;
    v_json_object JSON_OBJECT_T;
    v_nested_array JSON_ARRAY_T;
    v_result CLOB;

    -- Oracle固有の型を使用
    v_anydata SYS.ANYDATA;
    v_xmltype XMLTYPE;
    v_interval INTERVAL DAY TO SECOND;

    -- フィールド値の割り当てを複雑にする変数
    TYPE t_rec IS RECORD (
        id NUMBER,
        name VARCHAR2(100),
        json_data JSON_ARRAY_T
    );
    v_record t_rec;
BEGIN
    -- 新しいJSON配列を作成
    v_json_array := JSON_ARRAY_T();

    -- 配列に要素を追加
    v_json_array.append('値1');
    v_json_array.append(123);

    -- JSONオブジェクトを作成
    v_json_object := JSON_OBJECT_T();
    v_json_object.put('name', p_name);
