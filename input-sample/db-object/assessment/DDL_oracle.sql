    OPEN c_default_sort;
    LOOP
        FETCH c_default_sort INTO v_record;
        EXIT WHEN c_default_sort%NOTFOUND;

        DBMS_OUTPUT.PUT_LINE('ID: ' || v_record.ID || ', 名前: ' || v_record.NAME || ', カナ: ' || v_record.KANA);
