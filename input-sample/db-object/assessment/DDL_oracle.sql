CREATE OR REPLACE PROCEDURE "SCHEMA_SAMPLE".SCT_0012_HIERARCHY_QUERY(
    p_root_id IN NUMBER DEFAULT 1
)
IS
    -- 階層クエリを使用したカーソル
    CURSOR c_hierarchy IS
        SELECT
            EMPLOYEE_ID,
            EMPLOYEE_NAME,
            MANAGER_ID,
            JOB_TITLE,
            LEVEL AS HIERARCHY_LEVEL,
            LPAD(' ', (LEVEL-1)*2) || EMPLOYEE_NAME AS TREE_DISPLAY,
            CONNECT_BY_ROOT EMPLOYEE_NAME AS ROOT_EMPLOYEE,
            SYS_CONNECT_BY_PATH(EMPLOYEE_NAME, '/') AS PATH,
            CONNECT_BY_ISLEAF AS IS_LEAF
        FROM
            T_0012
        START WITH
            EMPLOYEE_ID = p_root_id
        CONNECT BY
            PRIOR EMPLOYEE_ID = MANAGER_ID
        ORDER SIBLINGS BY
            EMPLOYEE_NAME;

    -- レコード変数
    v_emp_rec c_hierarchy%ROWTYPE;
BEGIN
    DBMS_OUTPUT.PUT_LINE('組織階層の表示:');
    DBMS_OUTPUT.PUT_LINE('-----------------------------');

    -- カーソルを開いて階層データを取得
    OPEN c_hierarchy;
    LOOP
        FETCH c_hierarchy INTO v_emp_rec;
        EXIT WHEN c_hierarchy%NOTFOUND;

        -- 階層データの表示
        DBMS_OUTPUT.PUT_LINE(
            'レベル: ' || v_emp_rec.HIERARCHY_LEVEL ||
            ', ID: ' || v_emp_rec.EMPLOYEE_ID ||
            ', 名前: ' || v_emp_rec.TREE_DISPLAY ||
            ', 役職: ' || v_emp_rec.JOB_TITLE ||
            CASE WHEN v_emp_rec.IS_LEAF = 1 THEN ', (リーフノード)' ELSE '' END
        );
    END LOOP;
    CLOSE c_hierarchy;

    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('パス情報:');
    DBMS_OUTPUT.PUT_LINE('-----------------------------');

    -- パス情報を表示するためのカーソル
    DECLARE
        CURSOR c_paths IS
            SELECT
                EMPLOYEE_ID,
                EMPLOYEE_NAME,
                SYS_CONNECT_BY_PATH(EMPLOYEE_NAME, '/') AS PATH
            FROM
                T_0012
            START WITH
                EMPLOYEE_ID = p_root_id
            CONNECT BY
                PRIOR EMPLOYEE_ID = MANAGER_ID
            ORDER BY
                PATH;

        v_path_rec c_paths%ROWTYPE;
    BEGIN
        OPEN c_paths;
        LOOP
            FETCH c_paths INTO v_path_rec;
            EXIT WHEN c_paths%NOTFOUND;

            DBMS_OUTPUT.PUT_LINE(
                'ID: ' || v_path_rec.EMPLOYEE_ID ||
                ', 名前: ' || v_path_rec.EMPLOYEE_NAME ||
                ', パス: ' || v_path_rec.PATH
            );
        END LOOP;
        CLOSE c_paths;
    END;

EXCEPTION
    WHEN OTHERS THEN
        IF c_hierarchy%ISOPEN THEN
            CLOSE c_hierarchy;
        END IF;
        DBMS_OUTPUT.PUT_LINE('エラーが発生しました: ' || SQLERRM);
        RAISE;
END SCT_0012_HIERARCHY_QUERY;
/



CREATE OR REPLACE PROCEDURE "SCHEMA_SAMPLE".SCT_0014_PIVOT_SAMPLE
IS
    -- 結果を格納する変数
    v_jan NUMBER;
    v_feb NUMBER;
    v_mar NUMBER;
    v_apr NUMBER;
BEGIN
    -- DUAL表を使ったPIVOT構文のサンプル
    -- まず、UNION ALLを使って複数行のデータを作成し、それをPIVOTする

    -- カーソルを使って結果を取得
    FOR r IN (
        SELECT *
        FROM (
            SELECT 'JAN' AS month, 100 AS sales FROM DUAL
            UNION ALL
            SELECT 'FEB' AS month, 150 AS sales FROM DUAL
            UNION ALL
            SELECT 'MAR' AS month, 200 AS sales FROM DUAL
            UNION ALL
            SELECT 'APR' AS month, 180 AS sales FROM DUAL
        )
        PIVOT (
            SUM(sales)
            FOR month IN (
                'JAN' AS jan,
                'FEB' AS feb,
                'MAR' AS mar,
                'APR' AS apr
            )
        )
    ) LOOP
        v_jan := r.jan;
        v_feb := r.feb;
        v_mar := r.mar;
        v_apr := r.apr;

        -- 結果を表示
        DBMS_OUTPUT.PUT_LINE('1月の売上: ' || v_jan);
        DBMS_OUTPUT.PUT_LINE('2月の売上: ' || v_feb);
        DBMS_OUTPUT.PUT_LINE('3月の売上: ' || v_mar);
        DBMS_OUTPUT.PUT_LINE('4月の売上: ' || v_apr);
        DBMS_OUTPUT.PUT_LINE('合計売上: ' || (v_jan + v_feb + v_mar + v_apr));
    END LOOP;

    -- 四半期ごとの集計を行うPIVOTの例
    DBMS_OUTPUT.PUT_LINE('---四半期ごとの集計---');
    FOR r IN (
        SELECT *
        FROM (
            SELECT
                CASE
                    WHEN month IN ('JAN', 'FEB', 'MAR') THEN 'Q1'
                    WHEN month IN ('APR', 'MAY', 'JUN') THEN 'Q2'
                    WHEN month IN ('JUL', 'AUG', 'SEP') THEN 'Q3'
                    ELSE 'Q4'
                END AS quarter,
                sales
            FROM (
                SELECT 'JAN' AS month, 100 AS sales FROM DUAL
                UNION ALL
                SELECT 'FEB' AS month, 150 AS sales FROM DUAL
                UNION ALL
                SELECT 'MAR' AS month, 200 AS sales FROM DUAL
                UNION ALL
                SELECT 'APR' AS month, 180 AS sales FROM DUAL
                UNION ALL
                SELECT 'MAY' AS month, 190 AS sales FROM DUAL
                UNION ALL
                SELECT 'JUN' AS month, 210 AS sales FROM DUAL
            )
        )
        PIVOT (
            SUM(sales)
            FOR quarter IN (
                'Q1' AS q1,
                'Q2' AS q2
            )
        )
    ) LOOP
        DBMS_OUTPUT.PUT_LINE('第1四半期の売上: ' || r.q1);
        DBMS_OUTPUT.PUT_LINE('第2四半期の売上: ' || r.q2);
    END LOOP;

    -- 複数の集計関数を使用したPIVOTの例
    DBMS_OUTPUT.PUT_LINE('---複数の集計関数を使用した例---');
    FOR r IN (
        SELECT *
        FROM (
            SELECT 'JAN' AS month, 100 AS sales, 5 AS orders FROM DUAL
            UNION ALL
            SELECT 'FEB' AS month, 150 AS sales, 7 AS orders FROM DUAL
            UNION ALL
            SELECT 'MAR' AS month, 200 AS sales, 10 AS orders FROM DUAL
        )
        PIVOT (
            SUM(sales) AS sum_sales,
            AVG(orders) AS avg_orders
            FOR month IN (
                'JAN' AS jan,
                'FEB' AS feb,
                'MAR' AS mar
            )
        )
    ) LOOP
        DBMS_OUTPUT.PUT_LINE('1月の売上合計: ' || r.jan_sum_sales || ', 平均注文数: ' || r.jan_avg_orders);
        DBMS_OUTPUT.PUT_LINE('2月の売上合計: ' || r.feb_sum_sales || ', 平均注文数: ' || r.feb_avg_orders);
        DBMS_OUTPUT.PUT_LINE('3月の売上合計: ' || r.mar_sum_sales || ', 平均注文数: ' || r.mar_avg_orders);
    END LOOP;

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('エラーが発生しました: ' || SQLERRM);
END SCT_0014_PIVOT_SAMPLE;
/



CREATE OR REPLACE PROCEDURE "SCHEMA_SAMPLE".SCT_0015_DYNAMIC_SEARCH(
    p_table_name IN VARCHAR2,
    p_search_conditions IN VARCHAR2 DEFAULT NULL,
    p_order_by IN VARCHAR2 DEFAULT NULL,
    p_max_rows IN NUMBER DEFAULT 100
)
IS
    TYPE t_ref_cursor IS REF CURSOR;
    v_cursor t_ref_cursor;
    v_sql VARCHAR2(32767);
    v_column_count NUMBER;
    v_desc_tab DBMS_SQL.DESC_TAB;
    v_cursor_id PLS_INTEGER;
    v_dummy PLS_INTEGER;
    v_column_value VARCHAR2(4000);
    v_row_count NUMBER := 0;
BEGIN
    -- 動的SQLの構築
    v_sql := 'SELECT * FROM ' || p_table_name;

    IF p_search_conditions IS NOT NULL THEN
        v_sql := v_sql || ' WHERE ' || p_search_conditions;
    END IF;

    IF p_order_by IS NOT NULL THEN
        v_sql := v_sql || ' ORDER BY ' || p_order_by;
    END IF;

    v_sql := 'SELECT * FROM (' || v_sql || ') WHERE ROWNUM <= :max_rows';

    DBMS_OUTPUT.PUT_LINE('実行するSQL: ' || v_sql);

    -- DBMS_SQLを使用してカラム情報を取得
    v_cursor_id := DBMS_SQL.OPEN_CURSOR;
    DBMS_SQL.PARSE(v_cursor_id, v_sql, DBMS_SQL.NATIVE);
    DBMS_SQL.DESCRIBE_COLUMNS(v_cursor_id, v_column_count, v_desc_tab);

    -- カラム名を表示
    DBMS_OUTPUT.PUT_LINE('----------------------------------------');
    FOR i IN 1..v_column_count LOOP
        DBMS_OUTPUT.PUT(RPAD(v_desc_tab(i).col_name, 20));
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('----------------------------------------');

    -- カーソルをクローズ（情報取得のみに使用）
    DBMS_SQL.CLOSE_CURSOR(v_cursor_id);

    -- 動的カーソルを使用してデータを取得
    OPEN v_cursor FOR v_sql USING p_max_rows;

    -- 結果を取得して表示
    LOOP
        -- 各行のデータを取得
        FETCH v_cursor INTO v_desc_tab;
        EXIT WHEN v_cursor%NOTFOUND;

        -- 各カラムの値を表示
        FOR i IN 1..v_column_count LOOP
            DBMS_OUTPUT.PUT(RPAD(NVL(TO_CHAR(v_desc_tab(i).col_name), ' '), 20));
        END LOOP;
        DBMS_OUTPUT.PUT_LINE('');

        v_row_count := v_row_count + 1;
    END LOOP;

    -- カーソルを閉じる
    CLOSE v_cursor;

    DBMS_OUTPUT.PUT_LINE('----------------------------------------');
    DBMS_OUTPUT.PUT_LINE('取得された行数: ' || v_row_count);

EXCEPTION
    WHEN OTHERS THEN
        IF v_cursor%ISOPEN THEN
            CLOSE v_cursor;
        END IF;
        IF DBMS_SQL.IS_OPEN(v_cursor_id) THEN
            DBMS_SQL.CLOSE_CURSOR(v_cursor_id);
