        EXIT WHEN c_items%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('レコード: ID=' || v_item_rec.ID || ', NAME=' || v_item_rec.NAME);
    END LOOP;

    -- カーソルを閉じる
    CLOSE c_items;

