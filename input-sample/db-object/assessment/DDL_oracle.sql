CREATE OR REPLACE PROCEDURE "SCHEMA_SAMPLE".SCT_0074_NLSSORT_JAPANESE
IS
    -- カーソルの宣言（静的SQL）
    CURSOR c_japanese_sort IS
        SELECT ID, NAME, KANA
        FROM T_0074
        ORDER BY NLSSORT(KANA, 'NLS_SORT=JAPANESE');

    CURSOR c_default_sort IS
        SELECT ID, NAME, KANA
        FROM T_0074
        ORDER BY KANA;

